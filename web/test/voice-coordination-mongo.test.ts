import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { MongoClient } from 'mongodb';
import { MongoRepository } from '../src/server/db/mongo-repository.ts';
import { BackboneService } from '../src/server/core/service.ts';
import { VoiceService } from '../src/server/voice/service.ts';
const uri=process.env.POKEPET_TEST_MONGODB_URI;
test('independent instances coordinate one provider call and recover the saved receipt',{skip:!uri},async t=>{
  assert.match(uri!,/^mongodb:\/\/127\.0\.0\.1:\d+$/);
  const client=new MongoClient(uri!);await client.connect();t.after(()=>client.close());
  const db=client.db(`pokepet_local_voice_coord_${Date.now()}_${randomUUID().slice(0,8)}`),repo=new MongoRepository(db);await repo.initialize();
  const backbone=new BackboneService(repo),player=await backbone.bootstrap(undefined,'Two instances');
  let started!:()=>void,release!:()=>void,calls=0;
  const entered=new Promise<void>(resolve=>{started=resolve;}),gate=new Promise<void>(resolve=>{release=resolve;});
  const scorer=async(text:string)=>{calls++;started();await gate;return {transcript:text,points:11,reason:'Care'};};
  const one=new VoiceService(db,backbone,undefined,scorer,new Map()),two=new VoiceService(db,backbone,undefined,scorer,new Map());
  const input={commandId:randomUUID(),text:'I played with my pet'};
  const first=one.reportText(player.token!,input);await entered;
  assert.equal((await two.lookup(player.token!,input.commandId)).status,'pending');
  await assert.rejects(two.reportText(player.token!,input),/voice_pending/);
  await assert.rejects(two.reportText(player.token!,{...input,text:'Different report'}),/command_conflict/);
  assert.equal(calls,1);release();await first;
  const result=await two.reportText(player.token!,input) as {duplicate:boolean;points:number;snapshot:{points:number}};
  assert.equal(result.duplicate,true);assert.equal(result.points,11);assert.equal(result.snapshot.points,11);assert.equal(calls,1);
  const jobs=await db.collection('voice_jobs').find().toArray();assert.equal(jobs.length,1);
  assert.ok(!JSON.stringify(jobs).includes(input.text),'input should not be persisted');
});
test('expired lease may repeat provider work but never duplicates awarded points',{skip:!uri},async t=>{
  assert.match(uri!,/^mongodb:\/\/127\.0\.0\.1:\d+$/);
  const client=new MongoClient(uri!);await client.connect();t.after(()=>client.close());
  const db=client.db(`pokepet_local_voice_lease_${Date.now()}_${randomUUID().slice(0,8)}`),repo=new MongoRepository(db);await repo.initialize();
  const backbone=new BackboneService(repo),player=await backbone.bootstrap(undefined,'Lease tester');
  let started!:()=>void,release!:()=>void;const entered=new Promise<void>(r=>{started=r;}),gate=new Promise<void>(r=>{release=r;});
  const slow=new VoiceService(db,backbone,undefined,async(text)=>{started();await gate;return {transcript:text,points:11,reason:'Slow'};},new Map());
  const fast=new VoiceService(db,backbone,undefined,async(text)=>({transcript:text,points:7,reason:'Retry'}),new Map());
  const input={commandId:randomUUID(),text:'I fed my pet'};
  const original=slow.reportText(player.token!,input);await entered;
  await db.collection('voice_jobs').updateOne({},{$set:{leaseUntil:new Date(0)}});
  const recovered=await fast.reportText(player.token!,input) as {points:number;snapshot:{points:number}};assert.equal(recovered.points,7);
  release();const late=await original as {points:number;duplicate:boolean;snapshot:{points:number}};
  assert.equal(late.duplicate,true);assert.equal(late.points,7);assert.equal(late.snapshot.points,7);
});
test('a known provider failure releases the claim for the same request to retry',{skip:!uri},async t=>{
  assert.match(uri!,/^mongodb:\/\/127\.0\.0\.1:\d+$/);
  const client=new MongoClient(uri!);await client.connect();t.after(()=>client.close());
  const db=client.db(`pokepet_local_voice_retry_${Date.now()}_${randomUUID().slice(0,8)}`),repo=new MongoRepository(db);await repo.initialize();
  const backbone=new BackboneService(repo),player=await backbone.bootstrap(undefined,'Retry tester');
  const bad=new VoiceService(db,backbone,undefined,async()=>{throw Error('offline');},new Map());
  const good=new VoiceService(db,backbone,undefined,async(text)=>({transcript:text,points:6,reason:'Play'}),new Map());
  const input={commandId:randomUUID(),text:'I played with my pet'};
  await assert.rejects(bad.reportText(player.token!,input),/offline/);
  assert.equal((await good.lookup(player.token!,input.commandId)).status,'not_found');
  const result=await good.reportText(player.token!,input) as {points:number;snapshot:{points:number}};
  assert.equal(result.points,6);assert.equal(result.snapshot.points,6);
});
