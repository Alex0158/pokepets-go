import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { MongoClient } from 'mongodb';
import { MongoRepository } from '../src/server/db/mongo-repository.ts';
import { BackboneService } from '../src/server/core/service.ts';
import { ProgressionService } from '../src/server/progression/service.ts';
import { createLocalApi } from '../src/server/core/http.ts';
const uri=process.env.POKEPET_STANDALONE_TEST_MONGODB_URI;
test('standalone activation fails explicitly while progression and waiting match stay intact',{skip:!uri},async t=>{
  assert.match(uri!,/^mongodb:\/\/127\.0\.0\.1:\d+$/);
  const client=new MongoClient(uri!,{serverSelectionTimeoutMS:2000});await client.connect();t.after(()=>client.close());
  assert.equal((await client.db('admin').command({hello:1})).setName,undefined,'Use a dedicated standalone for this test');
  const name=`pokepet_local_standalone_activation_${Date.now()}_${randomUUID().slice(0,8)}`;
  const db=client.db(name),repo=new MongoRepository(db);await repo.initialize();
  const battle=new BackboneService(repo),progress=new ProgressionService(db,battle);
  const a=await battle.bootstrap(undefined,'Standalone A'),b=await battle.bootstrap(undefined,'Standalone B');
  await progress.command(a.token!,randomUUID(),{kind:'mission',missionId:'sniff-safari',confirmed:true});
  await progress.command(a.token!,randomUUID(),{kind:'upgrade',stat:'attack'});
  const waiting=await battle.create(a.token!,{commandId:randomUUID(),petId:a.pet._id,opponentPlayerId:b.player._id});
  const id=waiting.snapshot.matchId,before=await progress.get(a.token!);
  const req=new Request(`http://127.0.0.1:3018/api/matches/${id}/join`,{method:'POST',headers:{origin:'http://127.0.0.1:3018','content-type':'application/json',cookie:`pokepet_session=${b.token}`},body:JSON.stringify({commandId:randomUUID(),petId:b.pet._id,expectedVersion:0})});
  const res=await createLocalApi(battle)(req);
  assert.equal(res.status,503);assert.deepEqual(await res.json(),{error:'transaction_support_required'});
  assert.deepEqual(await progress.get(a.token!),before);
  assert.equal((await battle.read(a.token!,id)).status,'waiting');
  assert.equal((await progress.get(b.token!)).points,0);
  console.log(`Standalone compatibility test retained isolated database: ${name}`);
});
