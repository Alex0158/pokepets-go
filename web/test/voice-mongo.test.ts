import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { MongoClient } from 'mongodb';
import { MongoRepository } from '../src/server/db/mongo-repository.ts';
import { BackboneService } from '../src/server/core/service.ts';
import { ProgressionService } from '../src/server/progression/service.ts';
import { VoiceService } from '../src/server/voice/service.ts';
const uri=process.env.POKEPET_TEST_MONGODB_URI;
test('voice awards are authoritative, idempotent and preserve points when provider fails',{skip:!uri},async t=>{
  assert.match(uri!,/^mongodb:\/\/127\.0\.0\.1:\d+$/);
  const client=new MongoClient(uri!);await client.connect();t.after(()=>client.close());
  const db=client.db(`pokepet_local_voice_${Date.now()}_${randomUUID().slice(0,8)}`),repo=new MongoRepository(db);await repo.initialize();
  const backbone=new BackboneService(repo),person=await backbone.bootstrap(undefined,'Voice tester'),progress=new ProgressionService(db,backbone);
  let calls=0,release!:()=>void,started!:()=>void;
  const entered=new Promise<void>(resolve=>{started=resolve;}),gate=new Promise<void>(resolve=>{release=resolve;});
  const voice=new VoiceService(db,backbone,async()=>{calls++;started();await gate;return {transcript:'I played with my dog',points:12,reason:'Playtime'};},async(text)=>({transcript:text,points:8,reason:'Care time'}));
  const input={commandId:randomUUID(),audioBase64:Buffer.from('test recording').toString('base64'),mimeType:'audio/webm'};
  assert.equal((await voice.lookup(person.token!,input.commandId)).status,'not_found');
  const first=voice.report(person.token!,input),second=voice.report(person.token!,input);
  await entered;assert.equal((await voice.lookup(person.token!,input.commandId)).status,'pending');release();
  const [a,b]=await Promise.all([first,second]) as Array<{points:number}>;
  assert.equal(a.points,12);assert.equal(b.points,12);assert.equal(calls,1);assert.equal((await progress.get(person.token!)).points,12);
  const retried=await voice.report(person.token!,input) as {duplicate:boolean;points:number;transcript:null};assert.equal(retried.duplicate,true);assert.equal(retried.transcript,null);assert.equal(calls,1);
  const lookup=await voice.lookup(person.token!,input.commandId);assert.equal(lookup.status,'committed');
  await assert.rejects(voice.report(person.token!,{...input,audioBase64:Buffer.from('different').toString('base64')}),/command_conflict/);
  const broken=new VoiceService(db,backbone,async()=>{throw Error('provider down');});
  await assert.rejects(broken.report(person.token!,{...input,commandId:randomUUID()}));assert.equal((await progress.get(person.token!)).points,12);
  const textInput={commandId:randomUUID(),text:'I fed my dog'};
  const textResult=await voice.reportText(person.token!,textInput) as {points:number};assert.equal(textResult.points,8);
  const textRetry=await voice.reportText(person.token!,textInput) as {duplicate:boolean};assert.equal(textRetry.duplicate,true);
  await assert.rejects(voice.reportText(person.token!,{...textInput,text:'Other words'}),/command_conflict/);
  assert.equal((await progress.get(person.token!)).points,20);
  const upgraded=await progress.command(person.token!,randomUUID(),{kind:'upgrade',stat:'health'});assert.equal(upgraded.snapshot.points,15);
  console.log('Voice test retained isolated local test database:',db.databaseName);
});
